  final dungeons = dungeonTemplates.values
      .where((d) => d.storyOrder != null && d.collectibleItemId != null)
      .toList();
  dungeons.sort(
    (a, b) => (a.storyOrder ?? 9999).compareTo(b.storyOrder ?? 9999),
  );
  return dungeons;
}
